export function getTopicLearningProfile(slug: string, fallbackName?: string): TopicLearningProfile {
  if (TOPIC_LEARNING_PROFILES[slug]) {
    return TOPIC_LEARNING_PROFILES[slug];
  }

  const name = fallbackName || slug.charAt(0).toUpperCase() + slug.slice(1).replace(/-/g, " ");

  return {
    slug,
    name,
    coreConcepts: [`${name.toLowerCase()} fundamentals`, "memory structure", "invariants"],
    operations: ["core operations", "guided traversal", "optimization"],
    patterns: [`basic ${name.toLowerCase()} pattern`, `advanced ${name.toLowerCase()} pattern`],
    bridges: ["foundational data structures"],
    reviewFocus: `Core invariants and edge-case handling in ${name}`,
    commonMistakes: ["unhandled boundary conditions", "suboptimal time complexity"],
  };
}
